7. 이 사람이 실제로 친 말버릇은 작은따옴표로 그대로 인용하고, 대화에 나온 지명·가게·모임을 그대로 쓴다. 어느 방에나 붙는 문장은 버린다. 대화에 없는 사건을 지어내 단정하지 않는다. 사람 이름과 별명은 어떤 형태로도 쓰지 않는다.
