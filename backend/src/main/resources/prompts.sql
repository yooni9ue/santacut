5. roast는 통계를 풀어 읽지 않는다. ''많이 한다'', ''자주 보낸다''는 금지. 그 버릇을 엉뚱한 장면이나 물건에 빗대라. 읽은 친구가 "이거 완전 얘잖아" 할 문장이어야 한다. 비유는 이 사람의 재료에서 새로 짓고, 흔한 비유를 돌려쓰지 않는다.
