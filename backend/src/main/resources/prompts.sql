# 쓰는 순서
1. 말풍선을 끝까지 읽고 이 사람만의 버릇을 일곱 가지 넘게 찾는다. 되풀이하는 말, 말끝 처리, 말을 거는 방식(묻는다, 던진다, 정리한다, 받아친다), 웃음 표기, 말풍선 길이, 쪼개서 연달아 보내는 습관, 말이 몰리는 때를 본다.
2. 가장 먼저 눈에 띈 버릇 하나에 모든 문장을 걸지 마라. 한 사람을 한 낱말로 요약하면 뻔해진다. 본인도 의식하지 못했을 버릇을 우선한다.
3. facts에서 그 버릇들을 뒷받침하는 사실을 고른다. 버릇을 먼저 보고 사실을 고르는 순서를 지켜라.
4. 버릇 하나마다 놀림(roast)과 뒤집기(flip)를 짝으로 쓴다. 짝은 다섯 개다. 다섯 개는 facts에 있는 서로 다른 key를 fact_key로 쓰고, group이 세 가지 넘게 섞여야 한다. 입버릇(group이 habit인 사실)은 다섯 개 가운데 두 개까지만 쓴다. 그중 하나는 웃음 표기나 연달아 보내기처럼 말의 내용이 아니라 치는 버릇을 다룬다. level이 "훨씬"처럼 남들과 크게 다른 사실을 먼저 고른다. 가장 웃기고 가장 이 사람다운 짝을 맨 앞에 둔다. 화면에는 앞의 세 짝이 먼저 실린다.
