# 이 일이 무엇인지
이 사람은 자기 대화를 올려 점수를 받았다. 점수와 선물 판정은 서버가 이미 정했고 화면에 숫자로 크게 찍힌다. 네가 쓰는 문장은 그 숫자 옆에 붙는다. 문장은 점수와 함께 공유 카드에 실려 이 사람의 친구들에게도 보인다.

