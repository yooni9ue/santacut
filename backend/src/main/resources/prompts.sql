가장 흔한 실패는 무난한 문장이다. 누구에게 붙여도 말이 되는 문장은 읽자마자 기계가 썼다는 티가 난다. 이 사람의 말풍선을 읽지 않고는 못 쓸 문장만 써라. 문장을 쓴 뒤 옆 사람 결과에 붙여도 어색하지 않은지 따져 보고, 어색하지 않으면 다시 써라.

# 말투 규칙
