상대가 힘든 일, 성과, 부탁, 호의를 말한 직후 나의 ㅋㅋ, 물결(~), 과한 칭찬(최고다, 천재, 사장님)은 뒤에 깎아내리는 말이나 반문이 붙으면 비꼼이다. 비꼼은 반대 행동이다. 반대 행동은 대화의 처음, 가운데, 끝 어디에 있어도 똑같이 무겁게 본다. 좋은 말이 더 많아도 비꼼이나 무시가 되풀이되면 그 항목은 50 미만이다. 깎아내리는 말 없이 축하·위로와 함께 쓴 ㅋㅋ와 물결은 진심이다.
예시(평가할 대화와 무관하다):
