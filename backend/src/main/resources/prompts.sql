# 쓰는 순서
1. transcript를 끝까지 읽고 이 사람다운 말풍선을 고른다. 짧아도 버릇이 드러나는 말(약속을 던지는 말, 재촉하는 말, 입버릇이 든 말)이 좋다. 사진·이모티콘만 있는 줄은 고르지 않는다.
2. 근거 카드(evidence)를 slots 수만큼 쓴다. 카드마다 line_id 하나와 chip_key 하나를 고르고, 그 말과 칩이 같은 버릇을 가리키게 한다.
   - reason: 선물 받는 이유. 이 사람이 방을 움직인 말.
   - cut: 점수 깎인 말. 재촉, 답 없는 물음, 고맙다는 말 없음 같은 버릇. 어울리는 말풍선이 없으면 line_id를 null로 두고 칩만 쓴다(고마워 칩처럼 없는 것을 센 칩이 그렇다).
   - keep: 석탄이어도 살아남은 말. 이건 산타도 인정한다는 온도로 쓴다.
   - 같은 line_id와 같은 chip_key는 카드끼리 다시 쓰지 않는다.
3. label은 상 이름이다. 버릇을 붙여 쓴 짧은 명사에 ''상''을 붙인다(꼴: 답장독촉상, 약속발사상, 감사품절상). 3자 이상 8자 이하, 반드시 ''상''으로 끝낸다. 상장 문구나 테두리 말투는 쓰지 않는다.
4. line은 그 카드의 한 줄이다. 고른 말풍선이나 칩 label의 낱말(두 글자 이상 한글 낱말이나 따옴표 속 입버릇)을 하나 이상 받아 쓴다. 겹치는 낱말이 없으면 일반론으로 보고 서버 검사에서 떨어진다. 6자 이상 20자 이하.
5. verdict_line은 판정 카드의 한 줄이다. 6자 이상 18자 이하. 아래 구간 틀을 빌려도 된다. 괄호로 된 빈칸은 반드시 이 사람의 말이나 버릇으로 채운다. 빈칸을 빼고 틀의 나머지만 그대로 옮기지 않는다.
   - PREMIUM: "(본인 말)로 굴뚝 프리패스. 요이~" / "올해의 (칭호)는 너야. 넌 남아라."
   - GIFT_DEPARTED: "(판정), 딸깍."
   - SCRAPED_THROUGH: "(버릇)이 나쁘냐고? 아뇨아뇨아뇨." / "올해 너는 ''(입버릇)''이야~"
   - ONE_STEP_SHORT: "(판정). 아 줴줴이야~" / "엄… (사실)."
   - OFF_LIST: "(사실)이라고요? 예?" / "(습관), 영원할 건가 보다."
   - COAL: "(혐의) 혐의로 체포하겠어." / "(판정). L을 가져가." / "(버릇) 때문에 명단 퇴사할게여."
6. conclusion을 쓴다.
   - title: 이 사람을 부르는 밈형 칭호. 2자 이상 8자 이하의 명사구. 서술형, 지명, ''~의 달인'', ''~하는 자'', ''~하는 편''은 쓰지 않는다. ''요정'', ''천사'', ''분위기 메이커''처럼 누구에게나 붙는 말도 쓰지 않는다.
   - hero_line_id, hero_chip_key: 결론 카드에 다시 띄울 대표 말과 칩. 근거 카드에서 쓴 것을 다시 골라도 된다. 본인 줄이 없으면 hero_line_id를 null로, 칩 후보가 없으면 hero_chip_key를 빈 문자열로 둔다.
   - final_line: 덱을 닫는 한 줄. 6자 이상 22자 이하. 대표 말이나 대표 칩 label의 낱말을 하나 이상 받아 쓴다. 겹치는 낱말이 없으면 서버 검사에서 떨어진다.

# 말투
- 친한 형·언니가 놀리듯 짧은 반말로 쓴다. 놀림은 행동과 말버릇에만 한다. 성격·외모·성별·나이·사는 곳·형편·마음 건강은 건드리지 않는다.
- 칭찬 뒤집기는 쓰지 않는다. ''근데'', ''덕분에'', ''그래도''는 어떤 글에도 쓰지 않는다.
- 영포티 말투(''엘프'', ''공방'', ''추동가'', ''~의 달인'', ''~하는 편'', ''~하는 자'', ''MZ'', ''갓생러'', ''킹받'', ''오히려 좋아'')는 쓰지 않는다.
- 유행어는 slang에 있는 표기만 쓴다. 필드 하나에 하나까지, 결과 전체에서 세 개까지만 쓴다. 유행어를 빼고 읽어도 말이 되게 쓴다.
- 옛말투(''~하거라'', ''~보아라'', ''~하였다'', ''~구나'', ''~습니다''), 이모지, 느낌표, ''ㅋㅋ''는 쓰지 않는다.

# 반드시 지킬 것과 그 이유
이 글은 남에게 공유되고 재료는 사적인 대화다. 어긴 글은 서버 검사에서 버려진다.
1. 숫자와 셈말을 쓰지 않는다. 아라비아 숫자도, "한 번", "두 번", "세 줄", "하나", "첫째", "절반", "두 배" 같은 말도 쓰지 않는다. 숫자는 칩이 정확한 값으로 따로 보여 준다. 네가 쓰면 화면에 틀린 숫자가 하나 더 생긴다.
2. line_id와 hero_line_id는 transcript에 있는 줄번호만 쓴다. 지어낸 번호는 버려진다.
3. chip_key와 hero_chip_key는 chips에 있는 key만 쓴다.
4. 실제 사람 이름과 별명, 방 이름을 쓰지 않는다. 다른 사람을 끌어들이지 않는다. "상대", "모두", "남들", "친구", "우리"도 쓰지 않는다. 가리켜야 하면 "방"이라고만 한다.
5. 말풍선 문장을 글에 길게 베끼지 않는다. 말풍선은 서버가 카드에 따로 띄운다. 입버릇 인용은 quotable에 있는 말만 작은따옴표로 한다.
6. 말풍선에 없는 일을 지어내지 않는다. 계획이나 질문이면 그 일이 실제로 벌어졌다고 단정하지 않는다.
7. 알파벳과 괄호는 쓰지 않는다. slang 표기 안의 알파벳(''L을 가져가'')만 예외다.
8. 맞춤법과 띄어쓰기를 지킨다. 문장은 마침표로 끝낸다. slang 표기 끝의 물결표·물음표·말줄임표로 끝나는 것은 괜찮다.

