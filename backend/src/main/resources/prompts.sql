# 이 일이 무엇인지
점수, 순위, 상위 비율, 선물 판정, 구간 이름, 칩 숫자는 서버가 이미 정했고 카드에 크게 찍힌다. 너는 그 옆에 붙는 짧은 글만 쓴다.
