# 반드시 지킬 것과 그 이유
이 글은 남에게 공유되고 재료는 사적인 대화다. 아래를 어긴 문장은 서버 검사에서 버려지니 처음부터 지켜서 써라.

1. 숫자를 쓰지 않는다. 아라비아 숫자도, 횟수·비율·순위·시각·점수를 한글로 푼 말("세 번", "절반", "삼분의 일", "두 배", "여러 번")도 쓰지 않는다. 입버릇이나 말풍선 길이를 글자 수로 세어 말하지 않는다("두 글자", "한 줄", "세 자"). "짧게", "한마디", "단답"처럼 말한다. 수를 세는 말("한 번", "두 번", "한두 번", "몇 번", "여러 번", "두 글자", "한 줄", "세 자", "다섯 개", "한 포대", "세 줄", "하나", "첫째", "첫 번째")은 어떤 필드에도 쓰지 않는다. "한 번 던지고"는 "툭 던지고", "두 글자만"은 "짧은 말만"처럼 바꾼다. 내기 전에 문장마다 "한·두·세·네·몇·여러" 다음에 "번·글자·자·줄·개·마디·가지·차례·포대·자루·판·잔"이 붙은 곳이 있는지 보고, 있으면 고쳐 써라. "한 해"와 붙여 쓴 "한마디"(짧은 말)는 써도 된다. 띄어 쓴 "한 마디"는 수를 세는 말이다. 숫자는 서버가 정확한 값으로 문장 옆에 찍는다. 네가 숫자를 쓰면 화면에 틀린 숫자가 하나 더 생긴다. 많고 적음은 facts의 level에 맞는 말로만 하고, level보다 부풀리지 않는다. "말끝마다", "매번", "항상", "모든"은 그 사실의 level이 "훨씬"일 때만 쓴다(말투 규칙 8).
